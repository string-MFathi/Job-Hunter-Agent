import os
import time
import imaplib
from email.message import EmailMessage
import httpx
from dotenv import load_dotenv

load_dotenv()

def test_sheet_webhook():
    webhook_url = os.getenv("JOB_SHEET_WEBHOOK_URL", "").strip()
    if not webhook_url.startswith("https://script.google.com/"):
        print("⚠️ [Sheet Test] Please set a valid JOB_SHEET_WEBHOOK_URL in .env")
        return False

    print("🔄 [Sheet Test] Testing 'append' action...")
    payload = {
        "action": "append",
        "company_name": "Test AI Corp",
        "job_title": "AI Agent Developer",
        "platform": "Wuzzuf",
        "official_email": "careers@test-ai-corp.com",
        "job_summary": "Building autonomous multi-agent pipelines in Python.",
        "source_url": "https://wuzzuf.net/jobs/p/test-123",
        "status": "جديد"
    }
    with httpx.Client(timeout=15.0, follow_redirects=True) as client:
        res = client.post(webhook_url, json=payload)
        print(f"✅ [Sheet Append Response]: {res.text}")

    time.sleep(2)
    print("🔄 [Sheet Test] Testing 'update_status' action...")
    update_payload = {
        "action": "update_status",
        "company_name": "Test AI Corp",
        "official_email": "careers@test-ai-corp.com",
        "new_status": "تم تجهيز المسودة (Test)"
    }
    with httpx.Client(timeout=15.0, follow_redirects=True) as client:
        res2 = client.post(webhook_url, json=update_payload)
        print(f"✅ [Sheet Update Response]: {res2.text}")
    return True

def test_gmail_draft():
    gmail_user = os.getenv("GMAIL_USER_EMAIL", "").strip()
    gmail_pass = os.getenv("GMAIL_APP_PASSWORD", "").replace(" ", "").strip()

    if not gmail_user or not gmail_pass or "ضع_" in gmail_user:
        print("⚠️ [Gmail Test] Please set GMAIL_USER_EMAIL and GMAIL_APP_PASSWORD in .env")
        return False

    print("🔄 [Gmail Test] Connecting to Gmail IMAP to create a test draft...")
    msg = EmailMessage()
    msg["Subject"] = "[TEST DRAFT] Autonomous AI Agent Reliability — Mohamed Fathi"
    msg["From"] = gmail_user
    msg["To"] = "careers@test-ai-corp.com"
    msg.set_content(
        "Hi Hiring Team,\n\n"
        "This is an automated test draft generated by your Personal Job Hunter Agent.\n\n"
        "Best regards,\nMohamed Fathi\n"
        "https://www.linkedin.com/in/mohamed-fathi-pm/ | https://github.com/string-MFathi"
    )

    try:
        with imaplib.IMAP4_SSL("imap.gmail.com", 993) as imap:
            imap.login(gmail_user, gmail_pass)
            # إضافة المسودة مباشرة في مجلد المسودات
            status, _ = imap.append('"[Gmail]/Drafts"', "", imaplib.Time2Internaldate(time.time()), msg.as_bytes())
            if status == "OK":
                print("✅ [Gmail Test] Draft created successfully! Check your Gmail Drafts folder.")
                return True
            else:
                print(f"⚠️ [Gmail Test] Unexpected status: {status}")
                return False
    except Exception as e:
        print(f"❌ [Gmail Test Error]: {e}")
        return False

if __name__ == "__main__":
    print("🚀 Starting Phase 1 Infrastructure Check...\n")
    test_sheet_webhook()
    print("-" * 50)
    test_gmail_draft()
